def sha(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def atomic_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=1, ensure_ascii=False)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def digest_ids(ids) -> str:
    return hashlib.sha256(np.asarray(ids, dtype="<i8").tobytes()).hexdigest()


def require_server() -> dict:
    if platform.node().casefold() != SERVER_HOST.casefold():
        raise RuntimeError("E3 runs only on server B / DESKTOP-RFFERM3")
    if Path(__file__).resolve().parents[2] != ROOT.resolve():
        raise RuntimeError(f"E3 root must be {ROOT}")
    from tools.server_gpu_admission import require_visible_gpu
    selected = require_visible_gpu()
    if not torch.cuda.is_available() or torch.cuda.device_count() != 1:
        raise RuntimeError("exactly one visible CUDA device required; no CPU fallback")
    return selected


def configure_precision() -> None:
    torch.set_float32_matmul_precision("highest")
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True


def build(key: str):
    if key in ("full", "no_dechirp", "no_rms", "no_pc", "no_damage", "unet"):
        from tools.unet_ablation.models import make_model
        return make_model(key)
    if key == "cn":
        from paper2.network import CorrectionNet
        return CorrectionNet()
    if key == "norm":
        from tools.unet_norm_screen.model import NoiseReferenceUNet
        return NoiseReferenceUNet()
    if key in ("frequency", "dilation"):
        os.environ["ISRJ2_FACTOR"] = key   # settings module reads this once at import
        from tools.unet_factor_screen.model import FactorUNet
        from tools.unet_factor_screen import settings
        if settings.FACTOR != key:
            raise RuntimeError("factor module already imported with another factor")
        return FactorUNet()
    if key == "hybrid":
        from tools.vp_1103_recovp_hybrid import ReCoVPHybrid
        return ReCoVPHybrid()
    raise ValueError(key)


def checkpoint_binding(cp: Path, seed: int) -> dict:
    """Accept a checkpoint only if a sidecar and/or completion record binds its SHA."""
    digest = sha(cp)
    bindings = {}
    sidecar = cp.with_suffix(".json")
    if sidecar.is_file():
        value = json.loads(sidecar.read_text(encoding="utf-8")).get("checkpoint_sha256")
        if value is not None:
            bindings["sidecar"] = value
    complete = cp.parent / "TRAINING_COMPLETE.json"
    if complete.is_file():
        value = json.loads(complete.read_text(encoding="utf-8")).get("milestones", {}).get("256")
        if value is not None:
            bindings["training_complete_milestone_256"] = value
    if not bindings:
        raise RuntimeError(f"no SHA binding for {cp}")
    if any(v != digest for v in bindings.values()):
        raise RuntimeError(f"checkpoint SHA mismatch {cp}: {bindings} vs {digest}")
    return {"checkpoint": str(cp), "checkpoint_sha256": digest, "bindings": sorted(bindings)}


def load(family: str, seed: int):
    tmpl, key, _ = FAMILIES[family]
    cp = OUTPUTS / tmpl.format(s=seed)
    binding = checkpoint_binding(cp, seed)
    payload = torch.load(cp, map_location="cpu", weights_only=False)
    if isinstance(payload, dict) and "seed" in payload and int(payload["seed"]) != seed:
        raise RuntimeError(f"checkpoint seed mismatch: {cp}")
    if isinstance(payload, dict) and "epoch" in payload and int(payload["epoch"]) != 256:
        raise RuntimeError(f"checkpoint epoch mismatch: {cp}")
    if key == "hybrid":
        identity = payload.get("identity", {})
        for name, digest in identity.get("source_sha256", {}).items():
            path = ROOT / name
            if not path.is_file() or sha(path) != digest:
                raise RuntimeError(f"Hybrid source binding stale: {name}")
    with torch.random.fork_rng(devices=[]):
        model = build(key)
    model.load_state_dict(payload.get("model", payload.get("state")), strict=True)
    return model.cuda().eval(), binding


def restore(model, key: str, states: np.ndarray) -> dict[str, np.ndarray]:
    """[n,4,3,8,T] observations -> restored waveforms of the same shape."""
    if key != "hybrid":
        from paper2.evaluation_1103_v4 import restore_model
        return {"main": restore_model(model, states, torch.device("cuda"))}
    flat = states.reshape(-1, states.shape[-1])
    final = np.empty_like(flat, dtype=np.complex64)
    stage1 = np.empty_like(final)
    with torch.inference_mode():
        for lo in range(0, len(flat), 192):
            hi = min(lo + 192, len(flat))
            iq = torch.from_numpy(np.stack((flat[lo:hi].real, flat[lo:hi].imag), 1).astype(np.float32)).cuda()
            f = model.factor(iq)
            final[lo:hi] = f["restored"].cpu().numpy()
            stage1[lo:hi] = f["stage1_restored"].cpu().numpy()
    return {"main": final.reshape(states.shape), "stage1": stage1.reshape(states.shape)}


def frame_scores(u, s, e, doppler, target_idx, full: bool):
    """Old-protocol CFAR ratios plus residual-coherence diagnostics (E10).

    u: [n,4,3,8,T] restored; s,e: [n,3,8,T]. Ratio = CUT power / local CA
    reference mean, nominal 436 reference cells. h0 = frame max over valid
    cells of J+E; target = max over target range +/-1 at nearest Doppler bin.
    """
    from paper2.evaluation_1103_v4 import nearest_doppler_bin
    from paper2.radar_eval import ca_cfar, doppler_process, pulse_compress
    pc, _ = pulse_compress(u)
    n, _, jt_count = u.shape[:3]
    keys = ["h0"] + (["h0_noise", "target", "target_nojam", "resid_peak_noise_units",
                      "resid_concentration", "resid_energy_ratio", "gain_error", "orth_error",
                      "e0_modification"] if full else [])
    out = {k: np.empty((n, jt_count)) for k in keys}
    if full:
        pe, _ = pulse_compress(e)
        pr, _ = pulse_compress(u[:, 2] - e)
    for p in range(n):
        for jt in range(jt_count):
            states = (2, 0, 3, 1) if full else (2,)
            for state in states:
                rd, bins = doppler_process(pc[p, state, jt])
                power = np.abs(rd) ** 2
                _, thr, valid, nr, alpha = ca_cfar(power, p_fa=MAIN_PFA)
                if nr != 436:
                    raise RuntimeError("CFAR reference geometry changed")
                mean = thr / alpha
                ratio = np.divide(power, mean, out=np.zeros_like(power), where=valid & (mean > 0))
                if state == 2:
                    out["h0"][p, jt] = ratio[valid].max()
                elif state == 0:
                    out["h0_noise"][p, jt] = ratio[valid].max()
                else:
                    tr = int(target_idx[p])
                    db = nearest_doppler_bin(float(doppler[p]), bins)
                    value = ratio[db, max(0, tr - 1):min(ratio.shape[1], tr + 2)].max()
                    out["target" if state == 3 else "target_nojam"][p, jt] = value
            if full:
                rd_r, _ = doppler_process(pr[p, jt])
                rd_e, _ = doppler_process(pe[p, jt])
                _, _, valid, _, _ = ca_cfar(np.abs(rd_e) ** 2, p_fa=MAIN_PFA)
                pr2, pe2 = np.abs(rd_r[valid]) ** 2, np.abs(rd_e[valid]) ** 2
                out["resid_peak_noise_units"][p, jt] = pr2.max() / max(pe2.mean(), 1e-300)
                out["resid_concentration"][p, jt] = pr2.max() / max(pr2.sum(), 1e-300)
    if full:
        r = (u[:, 2] - e).astype(np.complex128)
        ee = np.sum(np.abs(e.astype(np.complex128)) ** 2, axis=(-2, -1)).clip(1e-24)
        out["resid_energy_ratio"] = np.sum(np.abs(r) ** 2, axis=(-2, -1)) / ee
        out["e0_modification"] = np.sum(np.abs(u[:, 0].astype(np.complex128) - e) ** 2, axis=(-2, -1)) / ee
        sw = s.astype(np.complex128)
        response = u[:, 3].astype(np.complex128) - u[:, 2].astype(np.complex128)
        es = np.sum(np.abs(sw) ** 2, axis=(-2, -1)).clip(1e-24)
        gain = np.sum(np.conj(sw) * response, axis=(-2, -1)) / es
        resid = response - gain[..., None, None] * sw
        out["gain_error"] = np.abs(gain - 1) ** 2
        out["orth_error"] = np.sum(np.abs(resid) ** 2, axis=(-2, -1)) / es
    return out


def run_set(model, key, path: Path, full: bool):
    from paper2.evaluation_1103_v4 import states_from_components
    from paper2.radar_eval import target_peak_range
    with np.load(path, allow_pickle=False) as z:
        s, j, e = (z[k] for k in ("s", "j", "epsilon"))
        ids = z["parent_id"].copy()
        doppler = z["doppler_hz"].copy()
    target_idx = target_peak_range(s[:, 0])
    labels = ("main", "stage1") if key == "hybrid" else ("main",)
    parts = {lab: [] for lab in labels}
    for lo in range(0, len(ids), CHUNK):
        hi = min(lo + CHUNK, len(ids))
        states = states_from_components(s[lo:hi], j[lo:hi], e[lo:hi])
        restored = restore(model, key, states)
        for lab in labels:
            parts[lab].append(frame_scores(restored[lab], s[lo:hi], e[lo:hi], doppler[lo:hi],
                                           target_idx[lo:hi], full))
    merged = {lab: {k: np.concatenate([p[k] for p in parts[lab]]) for k in parts[lab][0]} for lab in labels}
    return merged, ids


def curve(cal_h0, ev):
    rows = []
    for pfa in PFA_GRID:
        thr = float(np.quantile(cal_h0.reshape(-1), 1 - pfa, method="higher"))
        rows.append({"target_frame_pfa": pfa, "threshold_ratio": thr,
                     "cal_frame_pfa": float((cal_h0 > thr).mean()),
                     "eval_frame_pfa_jammer": float((ev["h0"] > thr).mean()),
                     "eval_frame_pfa_noise": float((ev["h0_noise"] > thr).mean()),
                     "eval_pd": float((ev["target"] > thr).mean()),
                     "eval_pd_no_jammer": float((ev["target_nojam"] > thr).mean())})
    return rows


def evaluate_one(family: str, seed: int) -> None:
    folder = OUT / family / f"seed_{seed}"
    if (folder / "ROW.json").is_file():
        print("skip existing", family, seed, flush=True)
        return
    admission = require_server()
    configure_precision()
    torch.set_num_threads(4)
    cal_sha, eval_sha = sha(CAL), sha(EVAL)
    model, binding = load(family, seed)
    key = FAMILIES[family][1]
    t0 = time.perf_counter()
    cal, cal_ids = run_set(model, key, CAL, full=False)
    ev, ev_ids = run_set(model, key, EVAL, full=True)
    elapsed = time.perf_counter() - t0
    labels = {"main": family, "stage1": "ReCoVP-Stage1"}
    for lab in cal:
        name = labels[lab]
        sub = OUT / name / f"seed_{seed}"
        sub.mkdir(parents=True, exist_ok=True)
        tmp = sub / "SCORES.tmp.npz"
        np.savez_compressed(tmp, cal_parent_id=cal_ids, eval_parent_id=ev_ids, cal_h0=cal[lab]["h0"],
                            **{f"eval_{k}": v for k, v in ev[lab].items()})
        os.replace(tmp, sub / "SCORES.npz")
        rows = curve(cal[lab]["h0"], ev[lab])
        main = next(r for r in rows if r["target_frame_pfa"] == MAIN_PFA)
        acceptance = None
        old_variant = FAMILIES[family][2] if lab == "main" else None
        if old_variant is not None and OLD_ROWS.is_file():
            old = next((r for r in json.loads(OLD_ROWS.read_text(encoding="utf-8"))["rows"]
                        if r["variant"] == old_variant and int(r["seed"]) == seed), None)
            if old is not None:
                acceptance = {
                    "old_threshold": old["calibration_threshold_ratio"], "new_threshold": main["threshold_ratio"],
                    "threshold_rel_diff": abs(main["threshold_ratio"] / old["calibration_threshold_ratio"] - 1),
                    "old_eval_pd": old["test_pd"]["mean"], "new_eval_pd": main["eval_pd"],
                    "old_eval_pfa": old["test_frame_pfa_jammer"]["mean"], "new_eval_pfa": main["eval_frame_pfa_jammer"],
                    "old_checkpoint_sha256": old["checkpoint_sha256"],
                    "same_checkpoint": old["checkpoint_sha256"] == binding["checkpoint_sha256"]}
                acceptance["pass"] = bool(acceptance["same_checkpoint"] and acceptance["threshold_rel_diff"] < 1e-6
                                          and abs(acceptance["old_eval_pd"] - main["eval_pd"]) < 1e-12
                                          and abs(acceptance["old_eval_pfa"] - main["eval_frame_pfa_jammer"]) < 1e-12)
        diag = {k: float(np.mean(v)) for k, v in ev[lab].items() if k not in ("h0", "h0_noise", "target", "target_nojam")}
        diag["resid_peak_noise_units_median"] = float(np.median(ev[lab]["resid_peak_noise_units"]))
        diag["resid_concentration_median"] = float(np.median(ev[lab]["resid_concentration"]))
        atomic_json(sub / "ROW.json", {
            "family": name, "seed": seed, "epoch": 256, "created_utc": now(), "server": platform.node(),
            "gpu_admission": admission, **binding,
            "calibration_sha256": cal_sha, "evaluation_sha256": eval_sha,
            "calibration_parent_ids_sha256": digest_ids(cal_ids), "evaluation_parent_ids_sha256": digest_ids(ev_ids),
            "calibration_frames": int(cal[lab]["h0"].size), "evaluation_frames": int(ev[lab]["h0"].size),
            "curve": rows, "main_pfa": MAIN_PFA, "diagnostics_mean": diag, "acceptance_vs_20261116": acceptance,
            "inference_and_scoring_seconds": elapsed,
            "protocol": "copied from tools/post_ablation_analysis.py: frame-max CUT/CA-mean ratio on J+E, "
                        "method/seed threshold at empirical calibration quantile (method='higher'); detection "
                        "if target range +/-1 at nearest Doppler bin exceeds it. Jammer variants are frames."})
        print("done", name, seed, main, acceptance, flush=True)
    del model
    torch.cuda.empty_cache()


def check_data() -> None:
    with np.load(CAL, allow_pickle=False) as a, np.load(EVAL, allow_pickle=False) as b:
        cal_ids, ev_ids = a["parent_id"].copy(), b["parent_id"].copy()
    if np.intersect1d(cal_ids, ev_ids).size:
        raise RuntimeError("calibration/evaluation overlap")
    for p in PROTECTED:
        with np.load(p, allow_pickle=False) as z:
            ids = z["parent_id"].copy()
        if np.intersect1d(cal_ids, ids).size or np.intersect1d(ev_ids, ids).size:
            raise RuntimeError(f"equal-Pfa sets overlap {p.name}")
    if not (len(cal_ids) == 1024 and len(ev_ids) == 2048):
        raise RuntimeError("unexpected equal-Pfa set sizes")


def queue(families, seeds_override=None) -> None:
    """Sequential driver; one subprocess per (family, seed) keeps imports isolated."""
    check_data()
    atomic_json(OUT / "DATA_CHECK.json", {"stage": "PASS", "checked_utc": now(),
                                          "calibration_sha256": sha(CAL), "evaluation_sha256": sha(EVAL)})
    jobs = []
    for fam in families:
        seeds = seeds_override or BASELINE_SEEDS
        if fam == "ReCoVP-Hybrid" and not seeds_override:
            seeds = [s for s in (17, 29, 41, 53, 67, 79, 97, 109)
                     if (OUTPUTS / f"recovp_hybrid_seed{s}" / f"seed_{s}" / "TRAINING_COMPLETE.json").is_file()]
        jobs += [(fam, s) for s in seeds]
    for i, (fam, s) in enumerate(jobs):
        atomic_json(OUT / "QUEUE_STATUS.json", {"updated_utc": now(), "job": i + 1, "total": len(jobs),
                                                "family": fam, "seed": s})
        if (OUT / fam / f"seed_{s}" / "ROW.json").is_file():
            continue
        while True:
            from tools.server_gpu_admission import NoGpuAvailable, choose_gpu
            try:
                gpu = choose_gpu()
            except NoGpuAvailable:
                time.sleep(60)
                continue
            env = {**os.environ, "CUDA_VISIBLE_DEVICES": str(gpu["physical_gpu_index"]),
                   "CUDA_DEVICE_ORDER": "PCI_BUS_ID", "PYTHONUTF8": "1", "PYTHONDONTWRITEBYTECODE": "1"}
            code = subprocess.call([sys.executable, "-m", "tools.paper2_baseline_suite.equal_pfa_suite",
                                    "one", "--family", fam, "--seed", str(s)], cwd=str(ROOT), env=env)
            if code == 0:
                break
            if code == 3:      # GPU busy at recheck: wait and retry, never fall back
                time.sleep(60)
                continue
            atomic_json(OUT / fam / f"seed_{s}" / "FAILED.json", {"exit_code": code, "utc": now()})
            break
    atomic_json(OUT / "QUEUE_STATUS.json", {"updated_utc": now(), "stage": "QUEUE_DONE", "total": len(jobs)})


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("one", "queue"))
    parser.add_argument("--family", action="append")
    parser.add_argument("--seed", type=int, action="append")
    args = parser.parse_args()
    if args.action == "one":
        from tools.server_gpu_admission import NoGpuAvailable
        try:
            evaluate_one(args.family[0], args.seed[0])
        except NoGpuAvailable as exc:
            print("gpu busy", exc, flush=True)
            sys.exit(3)
    else:
        queue(args.family or list(FAMILIES), args.seed)


if __name__ == "__main__":
    main()
